-- Tabellen voor de Streamlit-in-Snowflake versie (zelfde velden als src/data/prestatie.json).
-- Elke rij heeft een vaste sleutel (WEEK + SECTIE/RIJ) zodat opslaan via MERGE werkt.

CREATE TABLE IF NOT EXISTS KPI_AFWIJKINGEN (
  WEEK STRING, SECTIE STRING, RIJ INT,
  KPI STRING, DATUM STRING, NORM STRING, ACTUEEL STRING,
  AFWIJKING STRING, IMPACT STRING, LOCATIE STRING,
  PRIORITEIT STRING, ESCALATIE STRING, CATEGORIE STRING, VERBETERACTIE STRING,
  GEWIJZIGD_OP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS ACTIES (
  WEEK STRING, RIJ INT, DATUM STRING, DEADLINE STRING,
  EIGENAAR STRING, OMSCHRIJVING STRING,
  GEWIJZIGD_OP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS LOPENDE_PDCA (
  WEEK STRING, RIJ INT, DATUM STRING, DEADLINE STRING,
  EIGENAAR STRING, OMSCHRIJVING STRING,
  GEWIJZIGD_OP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
